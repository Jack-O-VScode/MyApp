/* Month grid, the day panel, and the event editor.

   Repeating events are generated by the store, so a cell may hold occurrences
   that share one underlying record. An edit therefore has to ask what it
   applies to: this day only, or the whole series. */
window.CalendarView = (function () {
  'use strict';

  var WEEKDAYS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
  var MAX_CHIPS = 3;

  var els = {};
  var viewMonth;          // Date pinned to the 1st of the month on screen
  var selectedDate;       // 'YYYY-MM-DD'
  var editingId = null;
  var editingMaster = null;
  var occurrenceDate = '';
  var lastFocused = null;

  var MODES = ['day', 'week', 'month', 'year', 'agenda'];
  var mode = 'month';
  var narrow = window.matchMedia('(max-width: 560px)');

  /* ---------------------------------------------------------- formatting -- */

  function formatMonth(date) {
    return date.toLocaleDateString(undefined, { month: 'long', year: 'numeric' });
  }

  function formatDayLabel(key) {
    var date = Store.fromKey(key);
    // Long names wrap on a phone, so abbreviate there.
    var label = date.toLocaleDateString(undefined, narrow.matches
      ? { weekday: 'short', day: 'numeric', month: 'short' }
      : { weekday: 'long', day: 'numeric', month: 'long' });
    if (key === Store.todayKey()) return 'Today · ' + label;
    return label;
  }

  function formatTime(time) {
    return Fmt.time(time);
  }

  // "9:00 AM" stacked over "– 10:30 AM", for the lists that have the room.
  function fillTime(node, item) {
    node.textContent = formatTime(item.time);
    if (item.time && item.endTime) {
      var end = document.createElement('small');
      end.className = 'event-end';
      end.textContent = '– ' + formatTime(item.endTime);
      node.appendChild(end);
    }
  }

  // A small mark on an event that has notes written for it (that day of it).
  function noteMark(item) {
    if (!Store.notesForEvent(item.id, item.date).length) return null;
    var mark = document.createElement('span');
    mark.className = 'repeat-mark';
    mark.textContent = '📝 notes';
    return mark;
  }

  /* ------------------------------------------------------------ rendering -- */

  function renderWeekdays() {
    els.weekdays.innerHTML = '';
    WEEKDAYS.forEach(function (name) {
      var cell = document.createElement('div');
      cell.textContent = name;
      els.weekdays.appendChild(cell);
    });
  }

  function renderGrid() {
    var year = viewMonth.getFullYear();
    var month = viewMonth.getMonth();
    var start = new Date(year, month, 1);
    var leading = start.getDay();
    start.setDate(1 - leading);                      // back up to the Sunday
    var today = Store.todayKey();

    // Five or six weeks, whichever the month actually needs.
    var daysInMonth = new Date(year, month + 1, 0).getDate();
    var cells = Math.ceil((leading + daysInMonth) / 7) * 7;

    var first = Store.toKey(start);
    var last = Store.toKey(new Date(start.getFullYear(), start.getMonth(), start.getDate() + cells - 1));

    var byDate = {};
    Store.eventsInRange(first, last).forEach(function (item) {
      (byDate[item.date] = byDate[item.date] || []).push(item);
    });
    var tasksByDate = {};
    Store.allTasks({ openOnly: true }).forEach(function (task) {
      if (task.due >= first && task.due <= last) {
        (tasksByDate[task.due] = tasksByDate[task.due] || []).push(task);
      }
    });

    els.grid.innerHTML = '';
    var fragment = document.createDocumentFragment();

    for (var i = 0; i < cells; i++) {
      var date = new Date(start.getFullYear(), start.getMonth(), start.getDate() + i);
      var key = Store.toKey(date);
      var events = byDate[key] || [];
      var tasks = tasksByDate[key] || [];

      var cell = document.createElement('button');
      cell.type = 'button';
      cell.className = 'day';
      cell.dataset.date = key;
      cell.setAttribute('role', 'gridcell');
      if (date.getMonth() !== month) cell.classList.add('is-outside');
      if (date.getDay() === 0 || date.getDay() === 6) cell.classList.add('is-weekend');
      if (key === today) cell.classList.add('is-today');
      if (key === selectedDate) {
        cell.classList.add('is-selected');
        cell.setAttribute('aria-current', 'date');
      }

      var parts = [date.toLocaleDateString(undefined, { day: 'numeric', month: 'long' })];
      if (events.length) parts.push(events.length + (events.length === 1 ? ' event' : ' events'));
      if (tasks.length) parts.push(tasks.length + (tasks.length === 1 ? ' task' : ' tasks'));
      cell.setAttribute('aria-label', parts.join(', '));

      var number = document.createElement('span');
      number.className = 'day-number';
      number.textContent = date.getDate();
      cell.appendChild(number);

      events.slice(0, MAX_CHIPS).forEach(function (item) {
        var chip = document.createElement('span');
        chip.className = 'day-chip is-draggable';
        chip.dataset.id = item.id;
        chip.dataset.occ = item.date;
        if (item.color) chip.dataset.color = item.color;
        chip.textContent = item.time ? formatTime(item.time) + ' ' + item.title : item.title;
        cell.appendChild(chip);
      });
      tasks.slice(0, Math.max(0, MAX_CHIPS - events.length)).forEach(function (task) {
        var chip = document.createElement('span');
        chip.className = 'day-chip is-task is-draggable';
        chip.dataset.task = task.id;
        chip.dataset.occ = task.due;
        chip.textContent = '☐ ' + task.title;
        cell.appendChild(chip);
      });

      var hidden = events.length + tasks.length - MAX_CHIPS;
      if (hidden > 0) {
        var more = document.createElement('span');
        more.className = 'day-more';
        more.textContent = '+' + hidden + ' more';
        cell.appendChild(more);
      }

      // Narrow screens show dots instead of chips (see the stylesheet).
      if (events.length || tasks.length) {
        var dots = document.createElement('span');
        dots.className = 'day-dots';
        if (events.length) {
          var eventDot = document.createElement('span');
          eventDot.className = 'day-dot';
          dots.appendChild(eventDot);
        }
        if (tasks.length) {
          var taskDot = document.createElement('span');
          taskDot.className = 'day-dot is-task';
          dots.appendChild(taskDot);
        }
        cell.appendChild(dots);
      }

      fragment.appendChild(cell);
    }

    els.grid.appendChild(fragment);
  }

  // Sunday of the week a date falls in.
  function weekStart(key) {
    return Store.shiftKey(key, -Store.fromKey(key).getDay());
  }

  // What is on each day of a range, gathered in one pass.
  function gather(firstKey, lastKey) {
    var events = {};
    Store.eventsInRange(firstKey, lastKey).forEach(function (item) {
      (events[item.date] = events[item.date] || []).push(item);
    });
    var tasks = {};
    Store.allTasks({ openOnly: true }).forEach(function (task) {
      if (task.due >= firstKey && task.due <= lastKey) {
        (tasks[task.due] = tasks[task.due] || []).push(task);
      }
    });
    return { events: events, tasks: tasks };
  }

  // A week as seven columns, each the day's own little list. Not an hour grid:
  // an hour grid spends most of its height on the hours nobody has anything in.
  function renderWeek() {
    var start = weekStart(selectedDate);
    var end = Store.shiftKey(start, 6);
    var found = gather(start, end);
    var today = Store.todayKey();

    els.weekGrid.innerHTML = '';
    var fragment = document.createDocumentFragment();

    for (var i = 0; i < 7; i++) {
      var key = Store.shiftKey(start, i);
      var date = Store.fromKey(key);
      var events = found.events[key] || [];
      var tasks = found.tasks[key] || [];

      var column = document.createElement('button');
      column.type = 'button';
      column.className = 'week-day';
      column.dataset.date = key;
      column.setAttribute('role', 'gridcell');
      if (key === today) column.classList.add('is-today');
      if (key === selectedDate) {
        column.classList.add('is-selected');
        column.setAttribute('aria-current', 'date');
      }
      if (date.getDay() === 0 || date.getDay() === 6) column.classList.add('is-weekend');

      var head = document.createElement('span');
      head.className = 'week-day-head';
      var name = document.createElement('span');
      name.textContent = WEEKDAYS[date.getDay()];
      var number = document.createElement('span');
      number.className = 'week-day-number';
      number.textContent = date.getDate();
      head.appendChild(name);
      head.appendChild(number);
      column.appendChild(head);

      events.forEach(function (item) {
        var chip = document.createElement('span');
        chip.className = 'day-chip is-draggable';
        chip.dataset.id = item.id;
        chip.dataset.occ = item.date;
        if (item.color) chip.dataset.color = item.color;
        // The time is its own span so a narrow column can drop it: on a phone
        // "7:0..." says nothing, where the title at least names the thing.
        if (item.time) {
          var when = document.createElement('span');
          when.className = 'chip-time';
          when.textContent = formatTime(item.time);
          chip.appendChild(when);
        }
        chip.appendChild(document.createTextNode(item.title));
        column.appendChild(chip);
      });
      tasks.forEach(function (task) {
        var chip = document.createElement('span');
        chip.className = 'day-chip is-task is-draggable';
        chip.dataset.task = task.id;
        chip.dataset.occ = task.due;
        chip.textContent = '\u2610 ' + task.title;
        column.appendChild(chip);
      });
      if (!events.length && !tasks.length) {
        var blank = document.createElement('span');
        blank.className = 'week-day-blank';
        blank.textContent = '—';
        column.appendChild(blank);
      }

      fragment.appendChild(column);
    }
    els.weekGrid.appendChild(fragment);
  }

  // Twelve months at a glance. Days carry a dot when something is on, which is
  // all a year can usefully say in the space a year gets.
  function renderYear() {
    var year = viewMonth.getFullYear();
    var found = gather(year + '-01-01', year + '-12-31');
    var today = Store.todayKey();

    els.yearGrid.innerHTML = '';
    var fragment = document.createDocumentFragment();

    for (var month = 0; month < 12; month++) {
      var block = document.createElement('div');
      block.className = 'year-month';

      var title = document.createElement('button');
      title.type = 'button';
      title.className = 'year-month-name';
      title.dataset.month = String(month);
      title.textContent = new Date(year, month, 1)
        .toLocaleDateString(undefined, { month: 'long' });
      block.appendChild(title);

      var grid = document.createElement('div');
      grid.className = 'year-days';

      WEEKDAYS.forEach(function (name) {
        var head = document.createElement('span');
        head.className = 'year-weekday';
        head.textContent = name.charAt(0);
        grid.appendChild(head);
      });

      var leading = new Date(year, month, 1).getDay();
      for (var blankIndex = 0; blankIndex < leading; blankIndex++) {
        grid.appendChild(document.createElement('span'));
      }

      var days = new Date(year, month + 1, 0).getDate();
      for (var day = 1; day <= days; day++) {
        var key = Store.toKey(new Date(year, month, day));
        var cell = document.createElement('button');
        cell.type = 'button';
        cell.className = 'year-day';
        cell.dataset.date = key;
        cell.textContent = day;
        if (key === today) cell.classList.add('is-today');
        var busyEvents = (found.events[key] || []).length;
        var busyTasks = (found.tasks[key] || []).length;
        if (busyEvents || busyTasks) {
          cell.classList.add('is-busy');
          cell.setAttribute('aria-label', day + ': ' +
            [busyEvents ? busyEvents + ' events' : '', busyTasks ? busyTasks + ' tasks' : '']
              .filter(Boolean).join(', '));
        }
        grid.appendChild(cell);
      }

      block.appendChild(grid);
      fragment.appendChild(block);
    }
    els.yearGrid.appendChild(fragment);
  }

  /* ------------------------------------------------------------ timeline -- */

  var HOUR_PX = 48;
  var timelineDate = '';

  // "9 AM" or "09", following the clock setting — short enough for the gutter.
  function hourLabel(hour) {
    var options = { hour: 'numeric' };
    var twelve = Fmt.hour12();
    if (twelve !== undefined) options.hour12 = twelve;
    return new Date(2000, 0, 1, hour).toLocaleTimeString(undefined, options);
  }

  // Day view as hours: timed events are blocks you can drag up and down and
  // stretch, untimed ones sit in a strip above.
  function renderTimeline() {
    var items = Store.eventsOn(selectedDate);

    els.allDay.innerHTML = '';
    items.filter(function (item) { return !item.time; }).forEach(function (item) {
      var row = document.createElement('li');
      var chip = document.createElement('button');
      chip.type = 'button';
      chip.className = 'day-chip timeline-allday-chip';
      chip.dataset.open = item.id;
      chip.dataset.occ = item.date;
      if (item.color) chip.dataset.color = item.color;
      chip.textContent = item.title;
      row.appendChild(chip);
      els.allDay.appendChild(row);
    });
    els.allDay.hidden = !els.allDay.children.length;

    var grid = els.timelineGrid;
    grid.innerHTML = '';
    grid.style.height = (24 * HOUR_PX) + 'px';

    for (var hour = 0; hour < 24; hour++) {
      var line = document.createElement('div');
      line.className = 'timeline-hour';
      line.style.top = (hour * HOUR_PX) + 'px';
      line.dataset.hour = String(hour);
      var label = document.createElement('span');
      label.textContent = hour === 0 ? '' : hourLabel(hour);
      line.appendChild(label);
      grid.appendChild(line);
    }

    var blocks = Timeline.layout(items);
    blocks.forEach(function (block) {
      var item = block.item;
      var node = document.createElement('button');
      node.type = 'button';
      node.className = 'timeline-event';
      node.dataset.id = item.id;
      node.dataset.occ = item.date;
      node.dataset.start = String(block.start);
      node.dataset.end = String(block.end);
      node.dataset.hasEnd = item.endTime ? '1' : '';
      if (item.color) node.dataset.color = item.color;
      placeBlock(node, block.start, block.end);
      node.style.left = 'calc(var(--timeline-gutter) + (100% - var(--timeline-gutter)) * ' +
        (block.column / block.columns) + ')';
      node.style.width = 'calc((100% - var(--timeline-gutter)) / ' + block.columns + ' - 3px)';

      var title = document.createElement('span');
      title.className = 'timeline-title';
      title.textContent = item.title;
      var when = document.createElement('span');
      when.className = 'timeline-when';
      when.textContent = item.endTime
        ? formatTime(item.time) + ' – ' + formatTime(item.endTime)
        : formatTime(item.time);
      var handle = document.createElement('span');
      handle.className = 'timeline-resize';
      handle.setAttribute('aria-hidden', 'true');

      node.appendChild(title);
      node.appendChild(when);
      node.appendChild(handle);
      node.setAttribute('aria-label', item.title + ', ' + when.textContent);
      grid.appendChild(node);
    });

    if (selectedDate === Store.todayKey()) {
      var nowAt = new Date();
      var now = document.createElement('div');
      now.className = 'timeline-now';
      now.style.top = ((nowAt.getHours() * 60 + nowAt.getMinutes()) / 60 * HOUR_PX) + 'px';
      grid.appendChild(now);
    }

    // Open on the part of the day that matters, but only when the day changes:
    // re-rendering after a drag must not yank the view back.
    if (timelineDate !== selectedDate) {
      timelineDate = selectedDate;
      var first = blocks.length ? blocks[0].start : -1;
      var focus = selectedDate === Store.todayKey()
        ? new Date().getHours() * 60
        : (first >= 0 ? first : 8 * 60);
      els.timelineScroll.scrollTop = Math.max(0, (focus / 60 - 1) * HOUR_PX);
    }
  }

  function placeBlock(node, start, end) {
    node.style.top = (start / 60 * HOUR_PX) + 'px';
    node.style.height = Math.max(18, (end - start) / 60 * HOUR_PX - 2) + 'px';
    node.classList.toggle('is-short', end - start < 45);
  }

  // Moving or stretching a block on the timeline, in 15-minute steps.
  function timelineSession(node, gesture) {
    var resizing = !!gesture.target.closest('.timeline-resize');
    var start = Number(node.dataset.start);
    var end = Number(node.dataset.end);
    var landed = { start: start, end: end };
    var when = node.querySelector('.timeline-when');
    var scroller = els.timelineScroll;
    var scrolledFrom = scroller.scrollTop;
    node.classList.add('is-dragging');

    return {
      move: function (dx, dy, x, y) {
        // Near the top or bottom edge, keep scrolling so a block can travel
        // further than the visible hours.
        var box = scroller.getBoundingClientRect();
        if (y < box.top + 30) scroller.scrollTop -= 10;
        else if (y > box.bottom - 30) scroller.scrollTop += 10;

        var delta = Drag.snapMinutes(dy + scroller.scrollTop - scrolledFrom, HOUR_PX, 15);
        landed = Timeline.moved(start, end, delta, resizing);
        placeBlock(node, landed.start, landed.end);
        when.textContent = formatTime(Timeline.clockOf(landed.start)) +
          (resizing || node.dataset.hasEnd ? ' – ' + formatTime(Timeline.clockOf(landed.end)) : '');
      },
      end: function (commit) {
        node.classList.remove('is-dragging');
        if (!commit || (landed.start === start && landed.end === end)) {
          render();
          return;
        }
        var keepsEnd = resizing || !!node.dataset.hasEnd;
        var moved = Store.moveEvent(node.dataset.id, node.dataset.occ, {
          time: Timeline.clockOf(landed.start),
          endTime: keepsEnd ? Timeline.clockOf(landed.end) : ''
        });
        announceMove(moved, node.dataset.id);
        render();
      }
    };
  }

  // Carrying a chip from one day to another in the month or week grid.
  function daySession(container) {
    return function (chip) {
      var rect = chip.getBoundingClientRect();
      var ghost = chip.cloneNode(true);
      ghost.classList.add('drag-ghost');
      ghost.style.left = rect.left + 'px';
      ghost.style.top = rect.top + 'px';
      ghost.style.width = rect.width + 'px';
      document.body.appendChild(ghost);
      chip.classList.add('is-drag-source');
      var target = null;

      function setTarget(cell) {
        if (cell === target) return;
        if (target) target.classList.remove('is-drop-target');
        target = cell;
        if (target) target.classList.add('is-drop-target');
      }

      return {
        move: function (dx, dy, x, y) {
          ghost.style.transform = 'translate(' + dx + 'px, ' + dy + 'px)';
          var under = document.elementFromPoint(x, y);
          var cell = under && under.closest('[data-date]');
          setTarget(cell && container.contains(cell) ? cell : null);
        },
        end: function (commit) {
          ghost.remove();
          chip.classList.remove('is-drag-source');
          var date = target ? target.dataset.date : '';
          setTarget(null);
          if (!commit || !date || date === chip.dataset.occ) return;
          dropOnDay(chip, date);
        }
      };
    };
  }

  function dropOnDay(chip, date) {
    if (chip.dataset.task) {
      var task = Store.getTask(chip.dataset.task);
      if (!task) return;
      Store.saveTask({
        id: task.id, title: task.title, due: date, details: task.details, repeat: task.repeat
      });
    } else {
      announceMove(Store.moveEvent(chip.dataset.id, chip.dataset.occ, { date: date }), chip.dataset.id);
    }
    selectedDate = date;
    var moved = Store.fromKey(date);
    viewMonth = new Date(moved.getFullYear(), moved.getMonth(), 1);
    render();
  }

  // Dragging one day of a series leaves the rest where they were — say so,
  // because it is not obvious from the screen.
  function announceMove(result, originalId) {
    if (result && result.id !== originalId && window.App && App.toast) {
      App.toast('Moved this day only. Edit the event to move the whole series.');
    }
  }

  function renderDayPanel() {
    els.dayLabel.textContent = formatDayLabel(selectedDate);
    els.dayEvents.innerHTML = '';

    var events = Store.eventsOn(selectedDate);
    if (!events.length) {
      var empty = document.createElement('li');
      empty.className = 'empty';
      empty.textContent = 'Nothing planned yet.';
      els.dayEvents.appendChild(empty);
    } else {
      events.forEach(function (item) {
        var row = document.createElement('li');
        var button = document.createElement('button');
        button.type = 'button';
        button.className = 'event-item';
        button.dataset.id = item.id;
        if (item.color) button.dataset.color = item.color;

        var time = document.createElement('span');
        time.className = 'event-time';
        fillTime(time, item);

        var body = document.createElement('span');
        body.className = 'event-body';
        var title = document.createElement('span');
        title.className = 'event-title';
        title.textContent = item.title;
        body.appendChild(title);
        if (item.repeating) {
          var repeat = document.createElement('span');
          repeat.className = 'repeat-mark';
          repeat.textContent = 'repeats';
          title.appendChild(document.createTextNode(' '));
          title.appendChild(repeat);
        }
        var notes = noteMark(item);
        if (notes) {
          title.appendChild(document.createTextNode(' '));
          title.appendChild(notes);
        }
        if (item.details) {
          var details = document.createElement('p');
          details.className = 'event-details';
          details.textContent = item.details;
          body.appendChild(details);
        }

        button.appendChild(time);
        button.appendChild(body);
        row.appendChild(button);
        els.dayEvents.appendChild(row);
      });
    }

    // Tasks due that day sit under the schedule, so one screen answers
    // "what is happening" and "what do I owe" for the selected date.
    var tasks = Store.tasksOn(selectedDate);
    els.dayTasksWrap.hidden = !tasks.length;
    if (tasks.length) TasksView.fillList(els.dayTasks, tasks, '', { hideDueFor: selectedDate });
  }

  // Three weeks of everything, in one list. A month grid answers "what does
  // this month look like"; this answers "what is coming".
  function renderAgenda() {
    var start = Store.todayKey();
    var end = Store.shiftKey(start, 20);

    var byDate = {};
    Store.eventsInRange(start, end).forEach(function (item) {
      (byDate[item.date] = byDate[item.date] || { events: [], tasks: [] }).events.push(item);
    });
    Store.allTasks({ openOnly: true }).forEach(function (task) {
      if (!task.due) return;
      // Anything already overdue belongs on today, not in the past.
      var key = task.due < start ? start : task.due;
      if (key > end) return;
      (byDate[key] = byDate[key] || { events: [], tasks: [] }).tasks.push(task);
    });

    els.agendaBody.innerHTML = '';
    var days = Object.keys(byDate).sort();
    if (!days.length) {
      var empty = document.createElement('p');
      empty.className = 'empty';
      empty.textContent = 'Nothing in the next three weeks.';
      els.agendaBody.appendChild(empty);
      return;
    }

    days.forEach(function (key) {
      var group = document.createElement('section');
      group.className = 'agenda-day';

      var heading = document.createElement('h3');
      heading.className = 'agenda-date';
      heading.textContent = formatDayLabel(key);
      if (key === Store.todayKey()) heading.classList.add('is-today');
      group.appendChild(heading);

      var list = document.createElement('ul');
      list.className = 'event-list';
      byDate[key].events.forEach(function (item) {
        var row = document.createElement('li');
        var button = document.createElement('button');
        button.type = 'button';
        button.className = 'event-item';
        button.dataset.id = item.id;
        button.dataset.date = item.date;
        if (item.color) button.dataset.color = item.color;

        var time = document.createElement('span');
        time.className = 'event-time';
        fillTime(time, item);
        var body = document.createElement('span');
        body.className = 'event-body';
        var title = document.createElement('span');
        title.className = 'event-title';
        title.textContent = item.title;
        body.appendChild(title);
        button.appendChild(time);
        button.appendChild(body);
        row.appendChild(button);
        list.appendChild(row);
      });
      group.appendChild(list);

      if (byDate[key].tasks.length) {
        var tasks = document.createElement('ul');
        tasks.className = 'task-list';
        TasksView.fillList(tasks, byDate[key].tasks, '', { hideDueFor: key });
        TasksView.wireList(tasks);
        group.appendChild(tasks);
      }

      els.agendaBody.appendChild(group);
    });
  }

  // A span of days has to read naturally whatever order the locale puts the
  // fields in, so this is built from the parts rather than glued together:
  // "13 – 19 September 2026" here, "September 13 – 19, 2026" in the US.
  function spanLabel(start, end) {
    var full = { day: 'numeric', month: 'long', year: 'numeric' };
    var sameYear = start.getFullYear() === end.getFullYear();

    if (sameYear && start.getMonth() === end.getMonth()) {
      // Only the day differs, so the first day goes in front of the last one
      // wherever in the string the locale happens to have put it.
      var first = start.toLocaleDateString(undefined, { day: 'numeric' });
      return new Intl.DateTimeFormat(undefined, full).formatToParts(end)
        .map(function (part) {
          return part.type === 'day' ? first + ' – ' + part.value : part.value;
        }).join('');
    }

    // Crossing a month, the year is only worth saying once unless it changes too.
    return start.toLocaleDateString(undefined, sameYear ? { day: 'numeric', month: 'long' } : full) +
      ' – ' + end.toLocaleDateString(undefined, full);
  }

  // What the bar over the grid says, which is different for every mode.
  function rangeLabel() {
    if (mode === 'day') return formatDayLabel(selectedDate);
    if (mode === 'year') return String(viewMonth.getFullYear());
    if (mode === 'week') {
      return spanLabel(Store.fromKey(weekStart(selectedDate)),
        Store.fromKey(Store.shiftKey(weekStart(selectedDate), 6)));
    }
    return formatMonth(viewMonth);
  }

  // Back and forward move by whatever the mode is showing.
  function step(direction) {
    if (mode === 'day') selectedDate = Store.shiftKey(selectedDate, direction);
    else if (mode === 'week') selectedDate = Store.shiftKey(selectedDate, direction * 7);
    else if (mode === 'year') {
      viewMonth = new Date(viewMonth.getFullYear() + direction, viewMonth.getMonth(), 1);
    } else {
      viewMonth = new Date(viewMonth.getFullYear(), viewMonth.getMonth() + direction, 1);
    }
    // Day and week move the selection, so the month has to follow it.
    if (mode === 'day' || mode === 'week') {
      var moved = Store.fromKey(selectedDate);
      viewMonth = new Date(moved.getFullYear(), moved.getMonth(), 1);
    }
    render();
  }

  function render() {
    if (mode === 'agenda') {
      renderAgenda();
      return;
    }
    if (mode === 'week') renderWeek();
    else if (mode === 'year') renderYear();
    else if (mode === 'month') renderGrid();
    else if (mode === 'day') renderTimeline();

    els.monthLabel.textContent = rangeLabel();
    if (mode !== 'year') renderDayPanel();
  }

  function setMode(next) {
    mode = MODES.indexOf(next) === -1 ? 'month' : next;

    els.agenda.hidden = mode !== 'agenda';
    els.monthLayout.hidden = mode === 'agenda';
    els.monthLayout.dataset.mode = mode;

    // One card holds whichever grid the mode wants; the day panel comes along
    // for every mode that is about a day or a handful of them.
    els.grid.hidden = mode !== 'month';
    els.weekGrid.hidden = mode !== 'week';
    els.yearGrid.hidden = mode !== 'year';
    els.timeline.hidden = mode !== 'day';
    els.weekdays.hidden = mode !== 'month';
    if (mode !== 'day') timelineDate = '';

    Array.prototype.forEach.call(els.modes.querySelectorAll('[data-mode]'), function (chip) {
      chip.classList.toggle('is-on', chip.dataset.mode === mode);
    });
    render();
  }

  /* --------------------------------------------------------- event modal -- */

  function renderSwatches(selected) {
    els.colors.innerHTML = '';
    [''].concat(Store.colors()).forEach(function (name) {
      var swatch = document.createElement('button');
      swatch.type = 'button';
      swatch.className = 'swatch' + (name === selected ? ' is-on' : '');
      swatch.dataset.color = name;
      swatch.setAttribute('role', 'radio');
      swatch.setAttribute('aria-checked', name === selected ? 'true' : 'false');
      swatch.setAttribute('aria-label', name || 'Default');
      els.colors.appendChild(swatch);
    });
  }

  function chosenColor() {
    var on = els.colors.querySelector('.swatch.is-on');
    return on ? on.dataset.color : '';
  }

  function showScope(show) {
    els.scope.hidden = !show;
    if (show) els.scope.querySelector('input[value="occurrence"]').checked = true;
  }

  function currentScope() {
    if (els.scope.hidden) return 'series';
    var chosen = els.scope.querySelector('input[name="scope"]:checked');
    return chosen ? chosen.value : 'series';
  }

  function syncUntilField() {
    els.until.parentNode.hidden = !els.repeat.value;
  }

  // An end time without a start has nothing to end.
  function syncEndField() {
    var hasStart = !!els.eventTime.value;
    els.eventEnd.disabled = !hasStart;
    if (!hasStart) els.eventEnd.value = '';
    els.endField.classList.toggle('is-muted', !hasStart);
  }

  function openModal(eventId, dateKey, occurrence, presetTime) {
    editingId = eventId || null;
    editingMaster = eventId ? Store.getEvent(eventId) : null;
    occurrenceDate = occurrence || dateKey || selectedDate;
    lastFocused = document.activeElement;

    els.modalTitle.textContent = editingMaster ? 'Edit event' : 'New event';
    els.eventTitle.value = editingMaster ? editingMaster.title : '';
    els.eventDate.value = editingMaster
      ? (editingMaster.repeat ? occurrenceDate : editingMaster.date)
      : (dateKey || selectedDate);
    els.eventTime.value = editingMaster ? (editingMaster.time || '') : (presetTime || '');
    els.eventEnd.value = editingMaster ? (editingMaster.endTime || '') : '';
    els.eventDetails.value = editingMaster ? (editingMaster.details || '') : '';
    els.repeat.value = editingMaster ? (editingMaster.repeat || '') : '';
    els.until.value = editingMaster ? (editingMaster.repeatUntil || '') : '';
    renderSwatches(editingMaster ? (editingMaster.color || '') : '');
    els.remind.value = String(editingMaster && typeof editingMaster.remind === 'number'
      ? editingMaster.remind
      : Store.getSettings().defaultRemind);
    els.eventDelete.hidden = !editingMaster;
    els.eventError.hidden = true;
    var written = editingMaster ? Store.notesForEvent(editingMaster.id, occurrenceDate).length : 0;
    els.eventNotes.hidden = !editingMaster;
    els.eventNotes.textContent = written ? 'Open notes' : 'Add notes';

    syncUntilField();
    syncEndField();
    showScope(!!(editingMaster && editingMaster.repeat));

    els.modal.hidden = false;
    els.eventTitle.focus();
  }

  function closeModal() {
    els.modal.hidden = true;
    editingId = null;
    editingMaster = null;
    if (lastFocused && document.contains(lastFocused)) lastFocused.focus();
    lastFocused = null;
  }

  function showError(message) {
    els.eventError.textContent = message;
    els.eventError.hidden = false;
  }

  function submit(submitEvent) {
    submitEvent.preventDefault();
    var title = els.eventTitle.value.trim();
    var date = els.eventDate.value;

    if (!title) return showError('Give the event a title.');
    // Safari on older iOS has no date picker widget, so validate the text.
    if (!Store.isKey(date)) return showError('Pick a valid date.');
    if (els.until.value && !Store.isKey(els.until.value)) return showError('Pick a valid end date.');
    if (els.repeat.value && els.until.value && els.until.value < date) {
      return showError('The repeat cannot end before it starts.');
    }
    if (els.eventEnd.value && els.eventEnd.value <= els.eventTime.value) {
      return showError('It has to end after it starts.');
    }

    var scope = currentScope();
    Store.saveEvent({
      id: editingId,
      scope: scope,
      occurrenceDate: occurrenceDate,
      title: title,
      date: date,
      time: els.eventTime.value || '',
      endTime: els.eventEnd.value || '',
      details: els.eventDetails.value.trim(),
      color: chosenColor(),
      remind: Number(els.remind.value),
      repeat: els.repeat.value,
      repeatUntil: els.repeat.value ? els.until.value : '',
      // A new rule makes the old list of skipped days meaningless.
      resetSkips: !!(editingMaster && editingMaster.repeat !== els.repeat.value)
    });

    selectedDate = date;
    var moved = Store.fromKey(date);
    viewMonth = new Date(moved.getFullYear(), moved.getMonth(), 1);
    closeModal();
    render();
  }

  function removeEvent() {
    if (!editingId) return;
    var repeating = editingMaster && editingMaster.repeat;
    var scope = repeating ? currentScope() : 'series';

    var message = repeating && scope === 'occurrence'
      ? 'Remove just this day from the series?'
      : (repeating ? 'Delete the whole repeating event?' : 'Delete this event?');
    if (!window.confirm(message)) return;

    Store.deleteEvent(editingId, scope, occurrenceDate);
    closeModal();
    render();
  }

  // Meeting notes: one note per event (per day, for a repeating one), made on
  // first use and opened every time after.
  function openEventNotes() {
    if (!editingMaster) return;
    var master = editingMaster;
    var day = master.repeat ? occurrenceDate : master.date;
    var existing = Store.notesForEvent(master.id, day)[0];
    closeModal();
    if (existing) {
      NotesView.openNote(existing.id);
      return;
    }
    var label = Store.fromKey(day).toLocaleDateString(undefined, { day: 'numeric', month: 'short' });
    NotesView.newNote({ title: master.title + ' · ' + label, eventId: master.id, eventDate: day });
  }

  /* ------------------------------------------------------------ quick add -- */

  function quickHint() {
    var text = els.quickTitle.value.trim();
    var parsed = text ? QuickParse.parse(text) : null;
    if (!parsed) {
      els.quickHint.hidden = true;
      return;
    }
    // With no date in the text it goes on whichever day is picked, so say so.
    var shown = parsed.date ? parsed : Object.assign({}, parsed, { date: selectedDate });
    els.quickHint.hidden = false;
    els.quickHint.textContent = '“' + parsed.title + '” · ' + QuickParse.describe(shown, 'event').join(' · ');
  }

  function quickAdd(formEvent) {
    formEvent.preventDefault();
    var text = els.quickTitle.value.trim();
    if (!text) return;
    var parsed = QuickParse.parse(text);
    var date = parsed.date || selectedDate;
    Store.saveEvent({
      title: parsed.title,
      date: date,
      time: parsed.time,
      endTime: parsed.endTime,
      details: '',
      color: '',
      remind: Store.getSettings().defaultRemind,
      repeat: parsed.repeat,
      repeatUntil: parsed.repeatUntil
    });
    els.quickTitle.value = '';
    els.quickHint.hidden = true;
    selectedDate = date;
    var moved = Store.fromKey(date);
    viewMonth = new Date(moved.getFullYear(), moved.getMonth(), 1);
    render();
    if (window.App && App.toast) {
      App.toast('Added to ' + Store.fromKey(date).toLocaleDateString(undefined,
        { weekday: 'short', day: 'numeric', month: 'short' }));
    }
  }

  /* ----------------------------------------------------------------- api -- */

  function init() {
    els = {
      grid: document.getElementById('day-grid'),
      weekdays: document.getElementById('weekday-row'),
      monthLabel: document.getElementById('month-label'),
      dayLabel: document.getElementById('day-label'),
      dayEvents: document.getElementById('day-events'),
      dayTasks: document.getElementById('day-tasks'),
      dayTasksWrap: document.getElementById('day-tasks-wrap'),
      modal: document.getElementById('event-modal'),
      modalTitle: document.getElementById('event-modal-title'),
      eventTitle: document.getElementById('event-title'),
      eventDate: document.getElementById('event-date'),
      eventTime: document.getElementById('event-time'),
      eventEnd: document.getElementById('event-end'),
      endField: document.getElementById('event-end-field'),
      eventNotes: document.getElementById('event-notes'),
      timeline: document.getElementById('day-timeline'),
      allDay: document.getElementById('timeline-allday'),
      timelineScroll: document.getElementById('timeline-scroll'),
      timelineGrid: document.getElementById('timeline-grid'),
      quickTitle: document.getElementById('quick-event-title'),
      quickHint: document.getElementById('quick-event-hint'),
      eventDetails: document.getElementById('event-details'),
      eventDelete: document.getElementById('event-delete'),
      eventError: document.getElementById('event-error'),
      repeat: document.getElementById('event-repeat'),
      until: document.getElementById('event-until'),
      scope: document.getElementById('event-scope'),
      colors: document.getElementById('event-colors'),
      remind: document.getElementById('event-remind'),
      agenda: document.getElementById('agenda'),
      agendaBody: document.getElementById('agenda-body'),
      monthLayout: document.getElementById('month-layout'),
      weekGrid: document.getElementById('week-grid'),
      yearGrid: document.getElementById('year-grid'),
      modes: document.getElementById('calendar-modes')
    };

    selectedDate = Store.todayKey();
    viewMonth = new Date(new Date().getFullYear(), new Date().getMonth(), 1);

    renderWeekdays();
    TasksView.wireList(els.dayTasks);

    // Rotating a phone switches between the long and short day label.
    if (narrow.addEventListener) narrow.addEventListener('change', renderDayPanel);
    else if (narrow.addListener) narrow.addListener(renderDayPanel);

    document.getElementById('prev-month').addEventListener('click', function () { step(-1); });
    document.getElementById('next-month').addEventListener('click', function () { step(1); });
    document.getElementById('add-event').addEventListener('click', function () {
      openModal(null, selectedDate);
    });

    els.weekGrid.addEventListener('click', function (clickEvent) {
      var column = clickEvent.target.closest('.week-day');
      if (!column) return;
      selectedDate = column.dataset.date;
      render();
    });

    els.yearGrid.addEventListener('click', function (clickEvent) {
      var name = clickEvent.target.closest('.year-month-name');
      if (name) {
        // A month's name is a way into that month.
        viewMonth = new Date(viewMonth.getFullYear(), Number(name.dataset.month), 1);
        selectedDate = Store.toKey(viewMonth);
        setMode('month');
        return;
      }
      var cell = clickEvent.target.closest('.year-day');
      if (!cell) return;
      selectedDate = cell.dataset.date;
      var picked = Store.fromKey(selectedDate);
      viewMonth = new Date(picked.getFullYear(), picked.getMonth(), 1);
      setMode('day');
    });

    els.grid.addEventListener('click', function (clickEvent) {
      var cell = clickEvent.target.closest('.day');
      if (!cell) return;
      selectedDate = cell.dataset.date;
      var date = Store.fromKey(selectedDate);
      if (date.getMonth() !== viewMonth.getMonth() || date.getFullYear() !== viewMonth.getFullYear()) {
        viewMonth = new Date(date.getFullYear(), date.getMonth(), 1);
      }
      render();
    });

    els.grid.addEventListener('dblclick', function (clickEvent) {
      var cell = clickEvent.target.closest('.day');
      if (cell) openModal(null, cell.dataset.date);
    });

    els.dayEvents.addEventListener('click', function (clickEvent) {
      var item = clickEvent.target.closest('.event-item');
      if (item) openModal(item.dataset.id, selectedDate, selectedDate);
    });

    els.repeat.addEventListener('change', syncUntilField);
    els.eventTime.addEventListener('input', syncEndField);
    els.eventTime.addEventListener('change', syncEndField);
    els.eventNotes.addEventListener('click', openEventNotes);

    document.getElementById('quick-event').addEventListener('submit', quickAdd);
    els.quickTitle.addEventListener('input', quickHint);

    // Drag a chip to another day in the month and week grids; drag a block up,
    // down, or by its bottom edge on the Day timeline.
    Drag.attach(els.grid, { selector: '.is-draggable', start: daySession(els.grid) });
    Drag.attach(els.weekGrid, { selector: '.is-draggable', start: daySession(els.weekGrid) });
    Drag.attach(els.timelineGrid, { selector: '.timeline-event', start: timelineSession });

    els.timelineGrid.addEventListener('click', function (clickEvent) {
      var block = clickEvent.target.closest('.timeline-event');
      if (block) {
        openModal(block.dataset.id, block.dataset.occ, block.dataset.occ);
        return;
      }
      // An empty hour: a new event starting there.
      var box = els.timelineGrid.getBoundingClientRect();
      var hour = Math.floor((clickEvent.clientY - box.top) / HOUR_PX);
      if (hour < 0 || hour > 23) return;
      openModal(null, selectedDate, null, String(hour).padStart(2, '0') + ':00');
    });
    els.allDay.addEventListener('click', function (clickEvent) {
      var chip = clickEvent.target.closest('[data-open]');
      if (chip) openModal(chip.dataset.open, chip.dataset.occ, chip.dataset.occ);
    });

    els.colors.addEventListener('click', function (clickEvent) {
      var swatch = clickEvent.target.closest('.swatch');
      if (swatch) renderSwatches(swatch.dataset.color);
    });

    els.modes.addEventListener('click', function (clickEvent) {
      var chip = clickEvent.target.closest('[data-mode]');
      if (chip) setMode(chip.dataset.mode);
    });

    document.getElementById('agenda-add').addEventListener('click', function () {
      openModal(null, Store.todayKey());
    });

    els.agendaBody.addEventListener('click', function (clickEvent) {
      var item = clickEvent.target.closest('.event-item');
      if (item) openModal(item.dataset.id, item.dataset.date, item.dataset.date);
    });

    // Switching between "this day" and "the series" changes which date the
    // form is really editing.
    els.scope.addEventListener('change', function () {
      if (!editingMaster) return;
      els.eventDate.value = currentScope() === 'series' ? editingMaster.date : occurrenceDate;
    });

    document.getElementById('event-form').addEventListener('submit', submit);
    document.getElementById('event-cancel').addEventListener('click', closeModal);
    els.eventDelete.addEventListener('click', removeEvent);
    els.modal.addEventListener('mousedown', function (clickEvent) {
      if (clickEvent.target === els.modal) closeModal();
    });

    render();
  }

  return {
    init: init,
    render: render,
    isModalOpen: function () { return !els.modal.hidden; },
    closeModal: closeModal,
    goToday: function () {
      var now = new Date();
      selectedDate = Store.toKey(now);
      viewMonth = new Date(now.getFullYear(), now.getMonth(), 1);
      render();
    },
    selectDate: function (key) {
      selectedDate = key;
      var date = Store.fromKey(key);
      viewMonth = new Date(date.getFullYear(), date.getMonth(), 1);
      render();
    },
    newEvent: function (dateKey) { openModal(null, dateKey || selectedDate); },
    editEvent: function (id, date) { openModal(id, date, date); }
  };
})();
